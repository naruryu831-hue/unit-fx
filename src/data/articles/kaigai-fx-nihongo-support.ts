経理部門やコンプライアンス部門との連携が必要になる場合があり、一次対応より時間がかかる傾向があります。進捗を都度確認したい場合は、あらかじめ「いつ頃、どのチャネルで状況を確認できるか」をサポートに尋ねておくと、やり取りがスムーズになります。

