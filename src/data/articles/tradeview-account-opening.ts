基本通貨は口座開設後に変更できないことが多いため、入出金のしやすさや損益の把握のしやすさを考慮して選びましょう。レバレッジについても、口座開設時点で希望の数値を選択する形式が一般的ですが、開設後にマイページから変更できる業者・できない業者があるため、詳細な運用は公式サイトの案内に従ってください。

