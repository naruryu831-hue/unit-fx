・本人確認書類の画像が不鮮明: 反射や影で文字が読み取れない画像は再提出になることがあります。フラットな場所に置き、真上から撮影するとよいでしょう。
・住所確認書類の発行日が古い: 発行から一定期間内の書類が求められることが多いため、直近の書類を用意しましょう。
