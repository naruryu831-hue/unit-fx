・居住国
・氏名(ローマ字表記が求められる場合があります)
・生年月日
・電話番号
・メールアドレス
・基本通貨(米ドル建てなど)
・レバレッジの希望(後から変更できる場合もありますが、詳細は公式サイトで確認してください)

