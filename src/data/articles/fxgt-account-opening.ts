口座開設や入金の手順とあわせて、出金の仕組みも事前に把握しておくと安心です。FXGTを含む多くの海外FX業者は、マネーロンダリング防止の観点から「入金に利用した方法と同じ経路で、入金額の範囲内を出金する」というルール（出金原則）を採用しています。例えばクレジットカードで入金した分については、まず同じクレジットカードへ出金し、それを超える利益分については銀行振込や電子ウォレットなど別の方法で出金する、といった運用になっている場合があります。

