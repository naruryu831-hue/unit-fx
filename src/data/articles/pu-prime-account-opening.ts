・複数のメールアドレスでの重複登録: 同一人物が複数の口座を意図せず重複登録してしまうと、アカウントの統合や本人確認のやり直しが必要になることがあります。過去に登録した記憶がある場合は、先にマイページへのログインを試すか、サポートに確認しましょう。
・利用規約の未確認による規約違反: 両建て取引の悪用やボーナスの不正利用など、規約で禁止されている取引手法を知らずに行ってしまうと、口座凍結や出金保留の対象になることがあります。口座開設時に規約へ目を通しておきましょう。

