・海外FX業者全般に共通する点として、日本の金融庁の登録を受けていない業者を利用する取引となるため、国内業者と同等の投資者保護制度（例えば信託保全の枠組みなど）が同じ形で適用されるとは限らない
・キャンペーンやボーナスの内容は時期によって変更・終了することがあり、口座開設時点の条件が将来も継続する保証はない
・出金時には本人確認手続きの完了や、入金方法との整合性など、一定の手続き・条件が求められる場合がある
・レバレッジが高いほど、相場変動時の損益の振れ幅（リスク）も大きくなるため、取引経験が浅い場合はロット数や証拠金維持率の管理に注意が必要である
・海外FXの利益は総合課税の対象となり、国内FX業者と税制上の扱いが異なる点もあらかじめ理解しておく必要がある

これらの点は、HFMに限らず海外FX業者を利用するうえで共通して意識しておきたい内容でもあります。

