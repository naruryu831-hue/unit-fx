取引経験や金融資産の状況、投資の目的などについて、いくつかの質問に回答するアンケートが用意されている場合があります。これは各国の金融規制に基づく適合性の確認や、マネーロンダリング防止のための手続きの一環として行われるものです。正直に回答してください。

