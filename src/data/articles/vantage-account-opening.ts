入力内容を確認し、利用規約・プライバシーポリシーなどに同意したうえでフォームを送信します。送信後、登録したメールアドレス宛に確認メールが届きますので、メール内のリンクをクリックしてメールアドレスの認証を完了させてください。この時点で、口座番号やサーバー名などが記載されたメールが別途届くこともあります。取引プラットフォームへのログインに必要な情報になるため、削除せずに保管しておきましょう。

