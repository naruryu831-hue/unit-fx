・流動性の変化：銘柄や時間帯によって流動性（取引のしやすさ）が変わり、スプレッドが広がりやすい場面がある
・規制の観点：仮想通貨関連の規制は国や地域によって異なり、今後の規制動向によって取引条件やサービス提供状況が変わる可能性がある

