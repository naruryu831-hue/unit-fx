・入力したメールアドレスの誤り: 登録時にタイプミスがあると認証メールが届きません。入力欄をよく確認してから送信しましょう。
・出金先の情報の入力ミス: 銀行口座番号や名義の入力を誤ると、出金処理が遅れる原因になります。出金申請時は入力内容を再度確認しましょう。
・希望プラットフォームと口座タイプの組み合わせの誤り: 口座タイプによって対応するプラットフォームが決まっている場合があるため、選択前に対応関係を確認しましょう。
・複数のメールアドレスでの重複登録: 同一人物が複数の口座を意図せず重複登録してしまうと、アカウントの統合や本人確認のやり直しが必要になることがあります。過去に登録した記憶がある場合は、先にマイページへのログインを試すか、サポートに確認しましょう。

