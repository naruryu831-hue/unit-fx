・ログイン情報や本人確認書類の画像は、第三者と共有しない
・公共のWi-Fiなど、セキュリティが確保されていない回線でのログインは避ける

不審なメールやメッセージでログイン情報の再入力を求められた場合は、公式サイトのURLを直接入力してアクセスし直すか、サポートに事実確認をしてから対応するようにしてください。

