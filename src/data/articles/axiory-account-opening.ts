本人確認が完了すると、マイページ上のステータス表示が「認証済み」などに変わり、出金や一部の機能が利用できるようになります。逆に本人確認が未完了のままだと、入金はできても出金ができない、あるいは一定額以上の取引に制限がかかるといった運用になっている業者が多いため、口座開設の初期段階で済ませておくことをおすすめします。

