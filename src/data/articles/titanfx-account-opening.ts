ただし、スマートフォンの画面サイズでは、パソコンに比べてチャート分析や複数銘柄の同時確認がしづらい場合があります。腰を据えて相場分析を行いたい場合はパソコンを、外出先での簡単な確認や決済操作にはスマートフォンを、というように使い分けるとよいでしょう。

