損切りルールを決めても、実際の取引では「もう少し待てば」という感情が働き、ルール通りに実行できないことがあります。こうした場合は、逆指値注文を必ず発注しておく、取引記録をつけてルールを破った回数と結果を振り返る、取引数量を小さくして心理的な負担を減らす、といった対策が考えられます。

