・失敗例1：比較サイトに載っていた古いスプレッド数値を信じて口座タイプを決め、実際のコスト感覚とずれてしまう。回避策として、判断材料は必ず公式サイトの現行ページを参照する
・失敗例2：EAやスキャルピングを行う前提で口座タイプを選ばず、後から取引手法に制限があることに気づく。回避策として、口座開設前に取引手法の制限有無を規約で確認する
