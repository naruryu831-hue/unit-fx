・給与所得がない、または個人事業主の場合：所得控除の状況にもよりますが、一般的にFXを含む所得の合計が一定額（基礎控除額など）を超える場合に確定申告が必要になるとされています。
・扶養親族となっている学生・主婦などの場合：一定額を超える所得があると、扶養控除の対象から外れる可能性がある点にも注意が必要です。

